/** A kit car's catalogue entry from its row (`KitCarRow`). */
function kitEntry([id, source, kit, label, gear]: KitCarRow): Entry {
  const base = kitBase(id, source, kit, label);
  return {
    ...base,
    ...gear,
    id,
    label: label ?? base.label,
    dir: KIT,
    glb: kit,
    kit,
    textureFile: undefined,
    // A kit car builds its spare into its body (the UAZ-469's on its rear door), not the
    // sibling's pack wheel at `spareNode`.
    spareNode: undefined,
    // Nor the sibling pack body's loaded stance: `applyLoadedRideDrop` moves vertices
    // only, so a kit's pivots (needles, steering wheel) would stay `loadedRideDrop` above
    // their parts and turn them round a point that far off (the UAZ-2206's needles and
    // wheel, 37 mm, from sa_uaz330364). A kit's stance is its own spec's.
    loadedRideDrop: undefined,
    glassUvCell: undefined,
    paintUvCell: undefined,
    glassMaterial: KIT_GLASS_MATERIAL,
    clearGlass: true,
    paintStyle: 'solid-paint',
    wheelNodes: KIT_WHEEL_NODES,
    // Shod from the Soviet pack's sets, each design equally likely, rescaled to the kit's
    // own tyre; a Niva-family sibling keeps its own off-road pool.
    wheelSetPool: base.wheelSetPool === OFFROAD_WHEEL_SET_POOL ? OFFROAD_WHEEL_SET_POOL : DISTINCT_SOVIET_WHEEL_SETS,
    lights: KIT_LIGHTS,
    scale: 1,
  };
}

