import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';

import { imageLoader } from './groundtextures';
import { maxAnisotropy } from '../texturequality';

/**
 * THE TREE ASSETS: the atlases, the models and the layout they are cut in.
 *
 * WHAT IS BEING LOADED. `public/look` holds, per season, one deciduous atlas (four
 * species columns, each with a whole-tree sprite, six crown modules and a bark strip,
 * plus a tangent-space normal map), one conifer atlas (two columns of whorl slices, side
 * branches and a bark strip, in colour and in a separate cut-out alpha), and one impostor
 * atlas per group (16 views of each species at 256 px, with view-space normals for the
 * deciduous). Twenty-eight GLB models carry the trees themselves: four variants per
 * species, one per stem and card seed, each UV-mapped into its species' column.
 *
 * THE LAYOUT IS READ, NOT WRITTEN DOWN. Cell rectangles, column and row counts, the
 * species each column holds, the cell's world size and where the bark strip begins are
 * all in `public/look/manifest.json`, generated by the asset pipeline that produced the
 * files — and the pipeline is still growing them (a species is re-rendered in place, and
 * a re-render moves rectangles). A hard-coded rectangle is a broken tree the day an atlas
 * is rebuilt, so the manifest is fetched once and every number here comes from it. The
 * FILE NAMES are a table, the way `groundtextures.ts` names the ground's photographs:
 * they are the pipeline's naming convention, and a season is a table row.
 *
 * ONLY THE SEASONS IN PLAY ARE RESIDENT. The season is continuous and the atlas is a set
 * of four, so the material blends the two heaviest (`LookPalette.groundForestA/B`). Two
 * sets of 4K atlases is 150 MB of texture; four would be twice a phone's budget, so
 * `retainTreeTextures` is handed the pair and disposes whatever else has been loaded.
 * A pair changes a few times a game year, and the season's own weight rises over days, so
 * the newly-named set is in place long before it is more than a few percent of the mix.
 *
 * NOTHING HERE FAILS A WORLD. Fetching the manifest needs `fetch` and a GLB needs a
 * loader, and the headless tools have neither; both paths return null and the tree layer
 * simply does not exist, the contract the ground's photographs and the bushes' cards are
 * already on.
 */

/** The six species with an asset of their own, in the impostor atlases' own order. */
export type TreeSpecies = 'birch' | 'aspen' | 'oak' | 'lime' | 'spruce' | 'pine';

/** The two model atlases, whose layouts differ. */
export type TreeAtlasGroup = 'deciduous' | 'conifer';

/** Everything about the atlases' geometry that the renderer needs, from the manifest. */
export interface TreeLayout {
  /** Columns in the model atlas: u = (column + u) / columns. */
  readonly columns: Record<TreeAtlasGroup, number>;
  /** The column each species owns in its model atlas. */
  readonly column: Record<TreeSpecies, number>;
  /** The impostor atlas' row count and the row each species owns (row = v band). */
  readonly rows: Record<TreeAtlasGroup, number>;
  readonly row: Record<TreeSpecies, number>;
  /** Views round the tree in the impostor atlas. */
  readonly views: number;
  /** One impostor cell's world size, metres: the quad a tree is drawn as. */
  readonly cellM: number;
  /** One impostor cell's size in texels. */
  readonly cellPx: number;
  /**
   * The top-down v at which a model column stops being cards and becomes the bark strip.
   * Read from the manifest's px rectangle, so a re-render that moves the strip moves this
   * with it.
   */
  readonly barkFromV: Record<TreeAtlasGroup, number>;
  /** Which species lives in which atlas. */
  readonly group: Record<TreeSpecies, TreeAtlasGroup>;
  /** How many GLB variants each species and each of the two low models has. */
  readonly variants: Record<TreeSpecies, number>;
  readonly stumpVariants: number;
  readonly logVariants: number;
}

/** The five photographs a season's trees are drawn from, by file under `/look/`. */
export interface TreeSeasonFiles {
  readonly deciduous: string;
  readonly conifer: string;
  readonly coniferAlpha: string;
  readonly imposterDeciduous: string;
  readonly imposterConifer: string;
}

