/**
 * The normals and the conifer alpha are one file for the whole year: the crown geometry
 * the pipeline bakes them from is the same in every season (only the leaves' paint
 * changes), so the manifest names them without a season. They are never disposed.
 */
export const TREE_SHARED_FILES = {
  deciduousNormal: 'trees_deciduous_summer_n.webp',
  imposterDeciduousNormal: 'imposters_deciduous_summer_n.webp',
  imposterConiferNormal: 'imposters_conifer_n.webp',
} as const;

const SPECIES_NAMES = ['birch', 'aspen', 'oak', 'lime', 'spruce', 'pine'] as const;

interface ManifestFile {
  readonly group?: string;
  readonly file?: string;
  readonly size?: readonly [number, number] | null;
  readonly role?: string;
  readonly layout?: Record<string, unknown>;
}

let manifestPromise: Promise<TreeLayout | null> | null = null;

/**
 * The atlas layout, from `public/look/manifest.json`. The *summer* entries carry it: the
 * season is a paint, the layout is the sheet, and a season that is being re-rendered in
 * place must not take the layout with it.
 */
export function treeLayout(): Promise<TreeLayout | null> {
  manifestPromise ??= (async () => {
    try {
      const response = await fetch('/look/manifest.json');
      if (!response.ok) return null;
      const body = (await response.json()) as { files?: Record<string, ManifestFile> };
      return readLayout(body.files ?? {});
    } catch {
      return null;
    }
  })();
  return manifestPromise;
}

function layoutOf(files: Record<string, ManifestFile>, file: string): Record<string, unknown> {
  return files[file]?.layout ?? {};
}

function readLayout(files: Record<string, ManifestFile>): TreeLayout | null {
  const deciduous = layoutOf(files, 'trees_deciduous_summer.webp');
  const conifer = layoutOf(files, 'trees_conifer_summer_m.webp');
  const imposterDeciduous = layoutOf(files, 'imposters_deciduous_summer_d.webp');
  const imposterConifer = layoutOf(files, 'imposters_conifer_summer_d.webp');
  const speciesList = (source: Record<string, unknown>): string[] =>
    Array.isArray(source['column_species']) ? (source['column_species'] as string[]) : [];
  const rowList = (source: Record<string, unknown>): string[] =>
    Array.isArray(source['row_species']) ? (source['row_species'] as string[]) : [];
  // WHERE THE BARK STRIP BEGINS, in the top-down v every tree texture is read in: the
  // strip's own px rectangle over the sheet's height (the manifest measures px from the
  // top, as the sampler now does). Above this v a column's texels are bark, below it they
  // are cards — one test, and the same number for both atlases today.
  const barkFrom = (source: Record<string, unknown>, file: string): number => {
    const strip = source['bark_strip'] as { px?: { y?: number; h?: number } } | undefined;
    const height = files[file]?.size?.[1];
    const y = strip?.px?.y;
    if (typeof y === 'number' && typeof height === 'number' && height > 0) return y / height;
    return 0.75;
  };
  const deciduousSpecies = speciesList(deciduous);
  const coniferSpecies = speciesList(conifer);
  const deciduousRows = rowList(imposterDeciduous);
  const coniferRows = rowList(imposterConifer);
  if (deciduousSpecies.length === 0 || coniferSpecies.length === 0) return null;

  const column: Record<string, number> = {};
  for (const [index, name] of deciduousSpecies.entries()) column[name] = index;
  for (const [index, name] of coniferSpecies.entries()) column[name] = index;
  const row: Record<string, number> = {};
  for (const [index, name] of deciduousRows.entries()) row[name] = index;
  for (const [index, name] of coniferRows.entries()) row[name] = index;
  const variants: Record<string, number> = {};
  let stumpVariants = 0;
  let logVariants = 0;
  for (const file of Object.keys(files)) {
    const model = /^tree_([a-z]+)_(\d+)\.glb$/.exec(file);
    if (model) {
      const name = model[1]!;
      variants[name] = Math.max(variants[name] ?? 0, Number(model[2]) + 1);
      continue;
    }
    const low = /^tree_(stump|log)_(\d+)\.glb$/.exec(file);
    if (low) {
      const count = Number(low[2]) + 1;
      if (low[1] === 'stump') stumpVariants = Math.max(stumpVariants, count);
      else logVariants = Math.max(logVariants, count);
    }
  }
  const group: Record<string, TreeAtlasGroup> = {};
  for (const name of speciesList(deciduous)) group[name] = 'deciduous';
  for (const name of speciesList(conifer)) group[name] = 'conifer';
  for (const name of SPECIES_NAMES) {
    if (column[name] === undefined || row[name] === undefined || !variants[name]) return null;
  }
  const cellsX = Number(imposterDeciduous['cells_x']) || 16;
  const cellM = Number(imposterDeciduous['cell_world_m']) || 12.4;
  const cellPx = Number(imposterDeciduous['cell_px']) || 256;
  return {
    columns: {
      deciduous: Number(deciduous['columns']) || deciduousSpecies.length,
      conifer: Number(conifer['columns']) || coniferSpecies.length,
    },
    column: column as Record<TreeSpecies, number>,
    rows: {
      deciduous: Number(imposterDeciduous['rows']) || deciduousRows.length,
      conifer: Number(imposterConifer['rows']) || coniferRows.length,
    },
    row: row as Record<TreeSpecies, number>,
    views: Math.max(2, cellsX),
    cellM,
    cellPx,
    barkFromV: {
      deciduous: barkFrom(deciduous, 'trees_deciduous_summer.webp'),
      conifer: barkFrom(conifer, 'trees_conifer_summer_m.webp'),
    },
    group: group as Record<TreeSpecies, TreeAtlasGroup>,
    variants: variants as Record<TreeSpecies, number>,
    stumpVariants: Math.max(1, stumpVariants),
    logVariants: Math.max(1, logVariants),
  };
}

