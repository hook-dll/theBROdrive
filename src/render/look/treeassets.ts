// The photographs

const textures = new Map<string, THREE.Texture>();

/**
 * One tree texture, by file under `/look/`, loaded once and kept until
 * `retainTreeTextures` says the season it belongs to is out of play. Colour space is part
 * of the data: an albedo is sRGB so the sampler returns linear light, a cut-out mask and
 * a normal map are numbers and stay linear.
 */
export function treeTexture(file: string, srgb: boolean): THREE.Texture {
  const have = textures.get(file);
  if (have) return have;
  const loader = imageLoader();
  const texture = loader ? loader.load(`/look/${file}`) : new THREE.Texture();
  // THE TREE ATLASES ARE READ TOP-DOWN. A model's uv comes out of a glTF file, and glTF
  // measures v from the TOP of the image — which is why GLTFLoader loads a texture with
  // `flipY = false`; with three's default the whole sheet is mirrored, and a mirror of the
  // clump rows [0, 0.75] is the bark strip. The impostor cells are computed from the
  // manifest's own px rectangles, which are top-down too, so every tree texture uses this
  // one convention and no consumer has to remember which way round it is.
  texture.flipY = false;
  texture.wrapS = THREE.RepeatWrapping;
  // A model's bark strip wraps along the trunk (u runs past 1); nothing samples past v.
  texture.wrapT = THREE.ClampToEdgeWrapping;
  texture.minFilter = THREE.LinearMipmapLinearFilter;
  texture.magFilter = THREE.LinearFilter;
  texture.anisotropy = maxAnisotropy();
  texture.colorSpace = srgb ? THREE.SRGBColorSpace : THREE.NoColorSpace;
  texture.name = file;
  textures.set(file, texture);
  return texture;
}

/** Drops every tree texture but the named ones: the seasons in play are the ones loaded. */
export function retainTreeTextures(files: readonly string[]): void {
  const keep = new Set(files);
  for (const name of Object.values(TREE_SHARED_FILES)) keep.add(name);
  for (const [file, texture] of textures) {
    if (keep.has(file)) continue;
    texture.dispose();
    textures.delete(file);
  }
}

/** Every file the two named seasons need, for `retainTreeTextures`. */
export function treeSeasonFiles(a: number, b: number): string[] {
  const out: string[] = [];
  for (const index of [a, b]) {
    const season = TREE_SEASON_FILES[index % TREE_SEASON_FILES.length]!;
    out.push(season.deciduous, season.conifer, season.coniferAlpha, season.imposterDeciduous, season.imposterConifer);
  }
  return out;
}

