// The models

/** One model, as the renderer draws it: vertices, normals, atlas uv and the baked colours. */
export interface TreeModels {
  /** `[species][variant]`, in `SPECIES_NAMES` order. */
  readonly tree: readonly (readonly THREE.BufferGeometry[])[];
  readonly stump: readonly THREE.BufferGeometry[];
  readonly log: readonly THREE.BufferGeometry[];
}

export const SPECIES_ORDER: readonly TreeSpecies[] = SPECIES_NAMES;

/**
 * A model's vertex colours are the pipeline's per-leaf bake (how turned the leaf is, how
 * bright, how shaded — see the asset log) and are read by name, so the geometry is
 * normalised once on the way in: `aTreeCol` as three floats, no second uv set, and a
 * bounding sphere for culling. The GLB has no material: every colour a tree has comes from
 * an atlas, and every light from the game.
 */
function prepareModel(geometry: THREE.BufferGeometry): THREE.BufferGeometry {
  const colours = geometry.getAttribute('color');
  if (colours) {
    const out = new Float32Array(geometry.getAttribute('position').count * 3);
    for (let i = 0; i < out.length; i += 3) {
      out[i] = colours.getX(i / 3);
      out[i + 1] = colours.getY(i / 3);
      out[i + 2] = colours.getZ(i / 3);
    }
    geometry.setAttribute('aTreeCol', new THREE.BufferAttribute(out, 3));
    geometry.deleteAttribute('color');
  } else {
    geometry.setAttribute('aTreeCol', new THREE.BufferAttribute(new Float32Array(geometry.getAttribute('position').count * 3).fill(1), 3));
  }
  geometry.deleteAttribute('uv1');
  geometry.deleteAttribute('uv2');
  geometry.computeBoundingSphere();
  return geometry;
}

let modelsPromise: Promise<TreeModels | null> | null = null;

/**
 * Every tree model, loaded once. Twenty-eight small files (16-25 kB each, about 170
 * vertices apiece) and four low ones, so the whole set is one round of requests and no
 * streaming: a variant that is missing when its first tree is drawn is a hole in a wood.
 */
export function treeModels(layout: TreeLayout): Promise<TreeModels | null> {
  modelsPromise ??= (async () => {
    try {
      const loader = new GLTFLoader();
      const load = async (file: string): Promise<THREE.BufferGeometry> => {
        const scene = (await loader.loadAsync(`/look/${file}`)).scene;
        let source: THREE.BufferGeometry | null = null;
        scene.traverse((object) => {
          const mesh = object as THREE.Mesh;
          if (!source && mesh.isMesh) source = mesh.geometry;
        });
        if (!source) throw new Error(`${file} carries no mesh`);
        return prepareModel((source as THREE.BufferGeometry).clone());
      };
      const tree = await Promise.all(
        SPECIES_NAMES.map((name) =>
          Promise.all(
            Array.from({ length: layout.variants[name]! }, (_unused, variant) => load(`tree_${name}_${variant}.glb`)),
          ),
        ),
      );
      const stump = await Promise.all(
        Array.from({ length: layout.stumpVariants }, (_unused, variant) => load(`tree_stump_${variant}.glb`)),
      );
      const log = await Promise.all(
        Array.from({ length: layout.logVariants }, (_unused, variant) => load(`tree_log_${variant}.glb`)),
      );
      return { tree, stump, log };
    } catch {
      return null;
    }
  })();
  return modelsPromise;
}
